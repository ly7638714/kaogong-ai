// 智能训练：板块映射 + 出题/变式/诊断 系统提示词
import { SYS } from '../kb'

export const PLATE_MODE = {
  判断推理: 'luoji',
  言语理解: 'yanyu',
  图形推理: 'tutu',
  资料分析: 'ziliao',
  数量关系: 'shuliang',
  政治理论: 'zhengzhi',
  常识判断: 'changshi',
  类比推理: 'leibi',
  定义判断: 'dingyi'
}

export function buildTaskSys(kind, opts = {}) {
  if (kind === 'quiz') {
    const plate = opts.plate || ''
    return (
      (SYS ? SYS : '') +
      '\n\n━━━━━━━━━━━━━━━━━━━━━━━━\n【本次任务·模拟出题】\n你现在是资深公考命题老师。基于上面的方法论体系，出一道' +
      (plate || '所选板块') +
      '的模拟真题（单选题），质量要求：\n1. 题干表述贴合真题风格（公务员考试表述习惯），考点明确；\n2. 提供 4 个选项（A/B/C/D），其中 1 个正确、2 个为典型干扰项（对应板块的陷阱）、1 个明显错误；\n3. 给出答案解析（用对应方法论讲清为什么对/错）+ 考点 + 一句话秒杀规律。\n\n输出格式：\n### 📝 题目\n（题干）\nA. … B. … C. … D. …\n【正确答案】X\n### ✅ 答案解析\n（正确项分析+干扰项拆解）\n### 🎯 考点\n（所属考点/题型）\n### ⚡ 秒杀规律\n（一句话）'
    )
  }
  if (kind === 'variant') {
    const prev = opts.prev || ''
    return (
      (SYS ? SYS : '') +
      '\n\n━━━━━━━━━━━━━━━━━━━━━━━━\n【本次任务·变式检验（举一反三）】\n用户刚问过一道题并得到了讲解。请你出一道【考点、题型完全相同，但题干背景、数字、人物、场景等素材完全换新】的变式题，用于检验用户是否真正掌握了这个知识点。\n\n用户刚问的原题：\n' +
      String(prev).slice(0, 1000) +
      '\n\n要求：考点与解题思路保持一致，但题目素材全新；按同样格式输出（题目+4选项+【正确答案】X+答案解析+考点+秒杀规律），并在选项区结束后单独一行输出【正确答案】X。'
    )
  }
  if (kind === 'diag') {
    return (
      (SYS ? SYS : '') +
      '\n\n━━━━━━━━━━━━━━━━━━━━━━━━\n【本次任务·学习诊断报告】\n请依据下面提供的用户学习数据（各板块提问次数、正确情况、错题分布、复盘情况），生成一份简洁务实的学习诊断报告，包含：\n1. 📊 板块表现一览（按掌握度排序，强→弱，用表格）；\n2. 🔍 高频薄弱点与普遍错因；\n3. 🎯 分板块学习建议（每个板块给2-3条具体可执行建议）；\n4. ⏱️ 备考优先级建议。\n用 Markdown，语气鼓励但实事求是。'
    )
  }
  return SYS || ''
}
