export function coachOf(plate6) { return COACH[plate6] || null }

// 做错题时的讲解协议（附加到 sys；plate6 为空则给通用诚实规则）
export function wrongExplainPrompt(plate6, opts = {}) {
  const c = COACH[plate6]
  if (!c) return '\n【错题讲解】先确认用户答错的是哪一项、为什么选它；用题干/选项原文作证据定位错因，再给正确判定要点与防法；不要从头重讲整套方法论，不要责备。'
  const head = plate6 === '判断推理' || plate6 === '言语理解' || plate6 === '资料分析' || plate6 === '数量关系' ? '【错题讲解·' + plate6 + '专用】' : '【错题讲解·' + plate6 + '】'
  return '\n' + head + '请按本板块错因框架讲：' + c.wrong + (opts.userPick ? '（用户自述选了 ' + opts.userPick + '，请先针对该项定位）' : '') + '；开头用一句话复述“你错在哪一步”，结尾只给1条防法。'
}

// 普通讲解规则（供后续“板块选择条→讲解”使用；目前 KB 流程头已承载 explain，这里预留统一入口）
export function explainRuleOf(plate6) { const c = COACH[plate6]; return c ? c.explain : '' }