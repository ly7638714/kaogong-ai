// 入口：返回该板块+子题型的质量要求文本（注入出题 prompt；未命中用板块默认）
export function qualityMatrixText(plate, variant) {
  const rules = QM[plate]
  if (!rules) return ''
  const v = String(variant || '')
  const hit = rules.find((r) => r.match.some((k) => v.includes(k)))
  const spec = hit ? hit.spec : DEFAULT_SPEC[plate] || ''
  if (!spec) return ''
  return '【命题质量矩阵·本题型硬要求】' + spec + ' 未达上述任一条即视为质检不合格。'
}
