// kbFlow —— KB 流程头抽取与总览判定（S1：分层注入，防整板块长文稀释）
// S2 精校（v2）：①先剥“【当前模式…】”模式横幅；②“【…答题流程/每题按此走…】”这类是流程正文，不再误当子节截断；
// ③只在真正的子节边界截断（##/**/编号列表/其余普通【小节】），从而保留真正的答题流程段而非只剩标题。

// 子节边界：markdown 标题 / 加粗行 / 编号列表行 / 非流程类【小节】
// 括号头若带“流程/答题流程/底层逻辑/走）”等词，说明它是流程正文的开头，不属于要截断的子节
const SUB_HEAD = /\n#{1,3}\s|\n\*\*|\n\d+[.、、．]|\n【(?![^】]*(答题流程|每题按此走|走）|四层|底层逻辑))[^】]{2,26}】/

// 手工精校兜底：个别板块顶部是“回应风格/开场”而不是流程，算法抽不到时用此（源自各自 KB 内流程原文，≤460 字）
const KB_FLOW_FALLBACK = {
  luoji: '【判断推理·答题流程】①看提问句：先判题型（削弱/加强/前提/解释/推出/评价/选非）与问法方向；②找结论引词（因此/所以/据此/研究者认为/由此可见/结果显示）→抓结论；③找论据；④判结构（二句式=论据结论有重复→考搭桥/拆桥；一句式=论据是数据/背景→考他因/机制/样本；另有因果共存/实验对照/由果推因）；⑤用薛睿“美丑”逐项核对：正确项说明对应哪种美（另有他因/补全逻辑/建立联系/直接例子），错误项点名哪种丑（偷换/以偏概全/正确的废话/方向反）。选非题先圈“不/不能”。'
}

export function kbFlowHead(kbText, limit = 420) {
  const raw = String(kbText || '')
  if (!raw.trim()) return ''
  let s = raw.replace(/\r\n/g, '\n').replace(/\r/g, '\n')
  // ① 剥掉开头“模式横幅”与紧随其后的空行（横幅只是板块标题，不是方法正文）
  s = s.replace(/^\s*【当前模式[^】]*】\s*/, '')
  const cut = s.search(SUB_HEAD)
  let h = (cut > 8 ? s.slice(0, cut) : s).replace(/\s+/g, ' ').trim()
  if (h.length > limit) h = h.slice(0, limit) + '…'
  return h
}

// 手工流程兜底：板块 KB 顶部若被风格段占据、算法抽取不足时，由 buildSys 调用它（有则优先）
export function kbFlowFallback(modeKey) {
  return KB_FLOW_FALLBACK[modeKey] || ''
}

// 问“板块方法总览/怎么学/体系全貌”等 → 给整块 KB；否则只给流程头
export function isMethodOverview(q) {
  return /(方法总览|讲讲.*方法|这类题怎么(做|学)|体系|全貌|整体(讲|看)|方法论|目录|速查|框架)/.test(String(q || ''))
}