// ---------- 工具 ----------
function cnt(t, w) {
  if (!w) return 0
  let n = 0,
    i = 0
  while ((i = t.indexOf(w, i)) !== -1) { n++; i += w.length }
  return n
}

/** 多信号打分识别板块：返回 {name, score, conf, second, candidates} */
function scorePlate(t) {
  const sc = {}
  for (const p of PLATE_LIST) {
    const d = PLATE_DICT[p]
    let s = 0
    for (const w of d.s) s += cnt(t, w) * 3
    for (const w of d.a) s += cnt(t, w) * 2
    for (const w of d.w) s += cnt(t, w) * 1
    sc[p] = s
  }
  const rank = PLATE_LIST.slice().sort((a, b) => sc[b] - sc[a])
  const top = sc[rank[0]] || 0
  const second = sc[rank[1]] || 0
  if (!top) return { name: '', score: 0, conf: 0, second: 0, candidates: [] }
  // 平滑置信度：分母 +2，避免"只命中 1 个弱词就显示 100%"
  const conf = Math.max(0, Math.min(1, top / (top + second + 2)))
  const candidates = rank.filter((p) => sc[p] > 0).slice(0, 3)
  return { name: rank[0], score: top, conf: Math.round(conf * 100) / 100, second, candidates }
}

/** 板块内识别具体题型 */
export function detectSubType(t, plate) {
  const map = SUB_DICT[plate]
  if (!map) return { name: '', score: 0 }
  let best = '',
    bs = 0
  for (const k of Object.keys(map)) {
    let s = 0
    for (const w of map[k]) s += cnt(t, w)
    if (s > bs) { bs = s; best = k }
  }
  return { name: bs > 0 ? best : '', score: bs }
}

/** 子意图识别（顺序敏感：越具体越先判） */
function detectIntent(t, ctx = {}) {
  if (isQuizAsk(t)) return '出题' // 仅“帮我出题/练题”才判出题（真实题不进入出题协议）
  if (/(为什么(选|是)?\s*[A-Da-d])|(我选(的)?(是)?\s*[A-Da-d])|(选\s*[A-Da-d]\s*(不)?(对|错))|(哪里错|错在哪|为何不选)/.test(t)) return '判错解释'
  if (/(秒杀|技巧就行|只要(方法|技巧|结论)|快速判断|不用推导|一句话说|直接给(答案|结论))/.test(t)) return '只秒杀'
  if (ctx.curQ && /(上一题|上道题|刚才(那|这)?题|同理|和(刚|上)(才|面|一)|区别|有什么不同|这类题)/.test(t)) return '对比'
  if (/(什么是|是什么意思|怎么理解|概念|定义是|指的是|区别是什么)/.test(t) && !/[A-D][.、．:：]/.test(t)) return '概念'
  if (/[A-D][.、．:：]/.test(t) || /(求|解|怎么算|怎么做|哪项|哪个|哪一项|意在|主旨)/.test(t)) return '求解'
  return '其他'
}

/** 缺失要素检测（只在需要作答的意图下才提示） */
function detectMissing(t, intent, plate, ctx = {}) {
  const m = []
  const need = intent === '求解' || intent === '判错解释'
  if (!need) return m
  const optCnt = (t.match(/[A-D][.、．:：]/g) || []).length
  if (optCnt < 2) m.push('选项')
  const askWord = /(意在|主旨|中心|下列哪项|哪一项|哪个|由此|根据|求|填入|属于|削弱|加强|前提|推出|比重|增长|多少|相似)/.test(t)
  if (!askWord) m.push('问法')
  if (t.replace(/\s/g, '').length < 25 && !ctx.hasImg) m.push('题干')
  if (intent === '判错解释' && !/[A-Da-d]/.test(t)) m.push('我的答案')
  // 疑似图形/图表题却没附图
  const figLike = plate === '图形推理' || (plate === '资料分析' && /(表格|柱状图|折线图|饼图|如图|下图)/.test(t))
  if (figLike && !ctx.hasImg) m.push('配图')
  return m
}

/** 生成可执行的提示（最多 3 条，具体、不说废话） */
function buildHints(a) {
  const hs = []
  if (a.lowConf && a.plate.name) hs.push({ ic: '🤔', t: '板块不太确定，点下方标签确认一下，避免用错方法论' })
  else if (!a.plate.name) hs.push({ ic: '🧭', t: '还没识别出板块，补一句"这是资料分析/图推/逻辑判断…"会更准' })
  if (a.missing.includes('配图')) hs.push({ ic: '📷', t: '疑似图形/图表题，点 📷 附图，AI 才能复刻并标注规律' })
  if (a.missing.includes('选项')) hs.push({ ic: '🔤', t: '缺选项：贴上 A/B/C/D，AI 才能逐项点名陷阱' })
  if (a.missing.includes('问法')) hs.push({ ic: '❓', t: '缺问法：说明"问的是主旨/削弱/基期…"，判定更准' })
  if (a.missing.includes('题干')) hs.push({ ic: '📋', t: '题干偏短：把完整题目贴进来（或截图），别让 AI 猜' })
  if (a.missing.includes('我的答案')) hs.push({ ic: '✅', t: '说明你选了哪项，AI 会专门讲你为什么踩坑' })
  if (!hs.length && a.plate.name && !a.missing.length) hs.push({ ic: '👍', t: '信息挺全，可以直接发送' })
  return hs.slice(0, 3)
}

/** 快捷 chip：点一下就把模板文本插进输入框 */
function buildChips(a) {
  const cs = []
  if (a.missing.includes('题干')) cs.push({ t: '📋 贴题干', ins: '【题干】' })
  if (a.missing.includes('选项')) cs.push({ t: '🔤 贴选项', ins: '【选项】A. \nB. \nC. \nD. ' })
  if (a.missing.includes('我的答案')) cs.push({ t: '✅ 我的答案', ins: '【我的答案】' })
  if (a.intent === '求解') {
    cs.push({ t: '⚡ 只求秒杀', ins: '只要秒杀技巧和关键判断依据，不用完整推导。' })
    cs.push({ t: '🔍 讲透这道题', ins: '请逐个选项讲透，并点明我最容易踩的陷阱。' })
  }
  if (a.intent === '判错解释') cs.push({ t: '🎯 我为什么错', ins: '请只讲我选的那项错在哪、踩了哪类陷阱。' })
  if (a.intent === '对比') cs.push({ t: '🆚 与上一题的区别', ins: '和上一题在考点/陷阱/方法上有什么区别？' })
  if (a.intent === '概念') cs.push({ t: '📖 公考怎么考', ins: '这个知识点在公考里通常怎么考？给个例子。' })
  return cs.slice(0, 4)
}

/**
 * 主入口：把一段输入解析为结构化理解结果
 * @param {string} text 用户输入
 * @param {{hasImg?:boolean, curQ?:object|null, forcePlate?:string}} ctx 上下文
 * @returns {object} AskAnalysis
 */
export function analyzeAsk(text, ctx = {}) {
  const t = String(text == null ? '' : text)
  const trimmed = t.trim()
  const empty = trimmed.replace(/\s/g, '').length < 4 && !ctx.hasImg
  const base = {
    plate: { name: '', score: 0, conf: 0 },
    sub: { name: '', score: 0 },
    intent: '其他',
    missing: [],
    hints: [],
    chips: [],
    candidates: [],
    lowConf: false,
    empty
  }
  if (empty) return base
  const sp = scorePlate(trimmed)
  const intent = detectIntent(trimmed, ctx)
  // forcePlate：调用方已确定板块（如用户点选确认 / detectBanKuai 结果）→ 题型必须在该板块内推断，避免错配
  const forced = ctx.forcePlate && PLATE_LIST.indexOf(ctx.forcePlate) !== -1 ? ctx.forcePlate : ''
  const pname = forced || sp.name
  const sub = detectSubType(trimmed, pname)
  // 低置信：分数低且不显著，或第一二名咬得很紧（已强制指定板块时不再判低置信）
  const lowConf = !forced && !!sp.name && ((sp.conf < 0.55 && sp.score < 6) || sp.score - sp.second <= 1)
  const a = {
    plate: { name: pname, score: forced ? 99 : sp.score, conf: forced ? 1 : sp.conf },
    sub,
    intent,
    missing: detectMissing(trimmed, intent, pname, ctx),
    hints: [],
    chips: [],
    candidates: lowConf ? sp.candidates : [],
    lowConf,
    empty: false
  }
  a.hints = buildHints(a)
  a.chips = buildChips(a)
  return a
}

/**
 * 规则版「增强提问」：把口语化/残缺输入结构化，绝不编造题干数据
 * @returns {{text:string, changed:boolean}}
 */
export function enhanceAsk(text, ctx = {}) {
  const raw = String(text == null ? '' : text).trim()
  if (!raw) return { text: raw, changed: false }
  // 幂等：已是结构化骨架就不再套壳
  if (raw.indexOf('【题干】') !== -1 || raw.indexOf('【我想问】') !== -1) return { text: raw, changed: false }
  const a = analyzeAsk(raw, ctx)
  const optM = raw.match(/[A-D][.、．:：][\s\S]*/)
  const stem = (optM ? raw.slice(0, optM.index) : raw).trim()
  const opts = optM ? optM[0].trim() : ''
  const myAns = (raw.match(/我选(?:的)?(?:是)?\s*([A-Da-d])/) || raw.match(/为什么(?:选|是)\s*([A-Da-d])/) || [])[1] || ''
  const ASK_BY_INTENT = {
    判错解释: myAns ? `我选了 ${myAns.toUpperCase()}，请说明它错在哪、踩了哪类陷阱，并讲清正确项的依据` : '请说明我为什么会选错，正确项的判定依据是什么',
    只秒杀: '只要一句话秒杀规律 + 关键判断依据，不用完整推导',
    对比: '这道题和上一题在考点/陷阱/方法上有什么区别',
    概念: '请讲清这个知识点的定义，以及公考里通常怎么考',
    出题: '请按这个考点出一道带完整 A/B/C/D 选项的题让我先做',
    求解: '请给出答案，并逐个选项点明陷阱',
    其他: '请针对上面内容给出具体分析'
  }
  const L = []
  if (a.plate.name) L.push('【板块】' + a.plate.name + (a.sub.name ? '·' + a.sub.name + '题' : ''))
  else L.push('【板块】（不确定，请你先判断）')
  L.push('【题干】' + (stem || '（待补充：把完整题目贴在这里）'))
  L.push('【选项】' + (opts || 'A. \nB. \nC. \nD. '))
  if (myAns) L.push('【我的答案】' + myAns.toUpperCase())
  else if (a.intent === '判错解释') L.push('【我的答案】（填你选的字母）')
  L.push('【我想问】' + (ASK_BY_INTENT[a.intent] || ASK_BY_INTENT['其他']))
  return { text: L.join('\n'), changed: true }
}

