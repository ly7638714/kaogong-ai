// 科目级兜底：规则未命中时按该科目主流题型归类（规则先行，非猜测）
const ZHENTI_FALLBACK = {
  '判断推理': '逻辑判断',
  '言语理解': '中心理解',
  '资料分析': '综合',
  '数量关系': '综合',
  '常识判断': '综合',
  '政治理论': '时政'
}

// 归一化：去空白/首尾，便于正则稳定匹配
function norm(s) {
  return String(s || '').replace(/\s+/g, '')
}

export function classifyZhentiType(subject, stem) {
  const rules = ZHENTI_RULES[subject] || []
  const text = norm(stem)
  if (!text) return '综合'
  // 类比推理短题特征：整题很短且含一个冒号分隔（如「踢皮球:互相推诿」）
  if (subject === '判断推理' && /^[^。]{1,16}[:：][^。]{1,28}$/.test(text)) return '类比推理'
  for (const [type, re] of rules) {
    if (re.test(text)) return type
  }
  return ZHENTI_FALLBACK[subject] || '综合'
}

export { ZHENTI_RULES, ZHENTI_FALLBACK }
