import { parseMaterialQuiz } from '../src/utils/quiz.js'
const sample = `### 📄 材料
2024年某市全年地区生产总值（GDP）为8200亿元，比上年增长6.0%。其中，第一产业增加值280亿元，增长3.5%；第二产业增加值3680亿元，增长5.2%；第三产业增加值4240亿元，增长7.1%。全年居民人均可支配收入4.86万元，比上年增长5.6%。

| 指标 | 2024年 | 同比增速 |
|---|---|---|
| GDP（亿元） | 8200 | 6.0% |
| 第二产业（亿元） | 3680 | 5.2% |
| 第三产业（亿元） | 4240 | 7.1% |

### 第1题
2024年该市第三产业增加值占GDP的比重约为（　）。
A. 51.7% B. 45.8% C. 43.2% D. 38.6%
【正确答案】A
### ✅ 解析
比重=4240÷8200≈51.7%。B是第二产业占比（44.9%算错），C是用错基数，D是把GDP当分子。
### 第2题
2023年该市GDP约为（　）亿元。
A. 7800 B. 7736 C. 7650 D. 7900
【正确答案】B
### ✅ 解析
基期=8200÷1.06≈7736。A是简单相减，C是增速方向反，D是四舍五入错。
### 第3题
根据上述材料，以下能够推出的是（　）。
A. 2024年该市第三产业增加值占GDP比重较上年上升
B. 2024年该市第一产业增加值超过300亿元
C. 2024年该市居民人均可支配收入增速低于GDP增速
D. 2024年该市第二产业增加值较2023年下降
【正确答案】A
### ✅ 解析
A：第三产业增速7.1%>GDP增速6.0%，比重上升，可推出。B：第一产业280亿<300亿，错。C：居民收入增速5.6%<GDP增速6.0%，"低于"表述反了，错。D：第二产业增速5.2%为正，上升不是下降，错。`
const r = parseMaterialQuiz(sample, 3)
console.log('material:', r.material.slice(0, 50).replace(/\n/g, ' '), '...')
console.log('qs count:', r.qs.length)
r.qs.forEach((q, i) => {
  console.log(`Q${i+1}: ans=${q.answer} | stem=${q.stem.slice(0, 38)} | opts=${q.options.length} | explain=${q.explain ? q.explain.slice(0, 28) : 'EMPTY'}`)
})
