const LEGACY_ALIASES = {
  '逻辑判断::前提型': '前提假设型',
  '逻辑判断::假设': '前提假设型',
  '常识判断::地理': '地理常识',
  '言语理解::态度': '态度观点',
  '资料分析::隔年增长率': '隔年增长'
}

const allowed = new Set()
for (const plate of PLATES) {
  for (const variant of SUB_VARIANTS[plate] || []) allowed.add(plate + '::' + variant)
  for (const variant of EXTRA_VARIANTS[plate] || []) allowed.add(plate + '::' + variant)
}

function legacySpec(plate, variant) {
  const rules = QM[plate] || []
  const v = String(variant || '')
  const hit = rules.find((r) => r.match.some((k) => v.includes(k)))
  return hit ? hit.spec : (DEFAULT_SPEC[plate] || '')
}

function fromSubProfile(plate, variant, sub) {
  const analogy = plate === '类比推理'
  return [
    `${plate}·${variant}。${sub.style} 题干规格：${sub.stem}${analogy ? ' 只允许两词、三词或填空式短题干，不写故事、背景和长句；问法固定为“下列选项中，与题干逻辑关系最为相似的是（　）。”，不得轮换为其他变体。' : ''}`,
    sub.out || `正确项必须由题干按「${variant}」的标准解法唯一推出，且问法方向不得反置。`,
    sub.traps || '三个干扰项必须分别对应三种真实错解，不得用同类错误、空话或一眼荒谬项凑数。',
    analogy ? `难度只来自一级关系与一处二级辨析，保持真题式短题干，不靠堆叠关系层级或复杂背景。` : `难度来自「${variant}」本身的专业判断复杂度，不靠生僻背景、绕口表达或加长材料。`,
    `语言、材料密度、问法和选项措辞须贴近近年国考/省考${plate}真题；禁止AI套话、机械排比和模板腔。`
  ]
}

export function resolveQualityVariant(plate, variant) {
  const p = String(plate || '').trim()
  const v = String(variant || '').trim()
  if (!PLATES.includes(p) || !v) return ''
  const direct = p + '::' + v
  if (allowed.has(direct) || EXTRA_RUBRICS[direct]) return v
  const alias = LEGACY_ALIASES[direct]
  if (alias) return alias
  return ''
}

export function hasDedicatedQualityRubric(plate, variant) {
  return !!resolveQualityVariant(plate, variant)
}

export function qualityRubric(plate, variant) {
  const p = String(plate || '').trim()
  const resolved = resolveQualityVariant(p, variant)
  if (!resolved) return null
  const key = p + '::' + resolved
  const arr = EXTRA_RUBRICS[key] || (SUB_PROFILE[resolved] ? fromSubProfile(p, resolved, SUB_PROFILE[resolved]) : null)
  if (!arr) return null
  return { plate: p, variant: resolved, blueprint: arr[0], correct: arr[1], distractors: arr[2], difficulty: arr[3], authenticity: arr[4], dedicated: true }
}

function fallbackRubric(plate, variant) {
  const spec = legacySpec(plate, variant)
  if (!spec) return null
  return {
    blueprint: spec,
    correct: '正确项必须由题干和本板块标准解法唯一推出；选是/选非方向不得发生歧义。',
    distractors: '三个错误项必须分别对应三种真实错解路径，与正确项同层级、同维度且互斥。',
    difficulty: '难度必须来自本板块真实专业判断，不靠偏题怪题、文字绕口或空泛材料。',
    authenticity: '语言、材料、问法和选项必须贴近近年国考/省考真题，禁止AI套话和机械模板。'
  }
}

// 入口：返回该板块+子题型的质量要求文本（出题与质检共用；未命中才回退板块默认）
export function qualityMatrixText(plate, variant) {
  const p = String(plate || '').trim()
  if (!PLATES.includes(p)) return ''
  const r = qualityRubric(p, variant) || fallbackRubric(p, variant)
  if (!r) return ''
  return '【命题质量矩阵·' + p + '·' + (r.variant || '综合') + '】\n' +
    '①命题蓝图：' + r.blueprint + '\n' +
    '②唯一答案：' + r.correct + '\n' +
    '③三路干扰项：' + r.distractors + '\n' +
    '④难度分层：' + r.difficulty + '\n' +
    '⑤真题语言：' + r.authenticity + '\n' +
    '【五维验收硬线】以上五轴必须同时成立；任一轴做不到，整题作废重写，不得以“题意大致能懂”放行。'
}

export default { qualityMatrixText, qualityRubric, hasDedicatedQualityRubric, resolveQualityVariant }
