// 通用兜底问法（未列出的题型用与 ASK_RULES 一致的标准问法，安全）
export function askVariant(plate, variant, seq = 0) {
  if (!variant) return ''
  const pool = ASK_POOL[variant]
  if (!pool || !pool.length) return ''
  // 非确定轮换：seq 打底 + 随机抖动；同题型每次用不同变体
  const idx = (seq + Math.floor(Math.random() * pool.length)) % pool.length
  return pool[idx].replace('（　）', Q_MARK)
}

