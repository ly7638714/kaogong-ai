//  1. 零破坏：绝不改动【正确答案】输出格式、不破坏现有 解析/判题/质检 依赖的标准结构；
//  2. 非确定轮换：题型/问法用「扰动后的轮换」，既保证相邻不同，又不陷入死板循环；
//  3. 可复用：纯 JS，无 Vue 依赖，单题与组卷共用同一套 API。
// 素材域清单仅作参考，与 professor.js 各板块 themes 保持一致且真实可考，不做无依据杜撰。

const MEM_KEY = 'xc_gen_diver'      // { heads: { plate: [最近题干头(≤3),...] } }
const RECENT_HEAD_N = 3             // 同一板块记住最近 N 道题的题干头，下一题提示避开
const HEAD_LEN = 120                // 每题题干头保留长度（防记忆膨胀、token 可控）

function readMem() {
  try { const d = JSON.parse(localStorage.getItem(MEM_KEY) || 'null'); return d && typeof d === 'object' ? d : { heads: {} } }
  catch (e) { return { heads: {} } }
}
function writeMem(m) {
  try { localStorage.setItem(MEM_KEY, JSON.stringify(m)) } catch (e) {}
}
function stemHead(t) {
  return String(t || '').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim().slice(0, HEAD_LEN)
}

