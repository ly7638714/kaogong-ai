import { describe, test, expect } from 'vitest'
import { retrieveCards } from '../kb/retrieve'

const cases = [
  ['资料分析', '今年粮食增产一成，问实际增长多少', '成数与折数'],
  ['资料分析', 'GDP名义增速7.8%，CPI涨幅2.5%，求实际增速', '名义增速与实际增速'],
  ['资料分析', '土地成交额等于面积乘单价，问成交额同比增长', '乘积增长率·A=B×C'],
  ['资料分析', '贸易顺差等于出口减进口，求顺差增长率', '顺差逆差'],
  ['资料分析', '材料说将近500亿元，问边界理解', '模糊量词'],
  ['资料分析', '工资从1000涨到1200，涨到了原来的几倍', '发展速度'],
  ['资料分析', '文字材料很长，怎么快速定位数据', '文字材料阅读三步法'],
  ['资料分析', '打八折出售，问折数含义', '成数与折数'],
  ['资料分析', '415份数法怎么求增长量', '415份数法'],
  ['资料分析', '已知现期量和增长率求基期，用假设分配', '假设分配法'],
  ['资料分析', 'ABRX四要素是什么', 'ABRX'],
  ['资料分析', '分母截几位，选项差距怎么看', '截位直除进阶'],
  ['资料分析', '错题怎么复盘 知二求三', '知二求三复盘法'],
  ['资料分析', '圈时间圈主体 防选非 刷题', '避坑动作链'],
]
describe('v3.7.95 新卡检索冒烟', () => {
  test('新卡被典型问法命中', () => {
    for (const [plate, q, expectType] of cases) {
      const hits = retrieveCards(plate, q, 3).map(c => c.type)
      expect(hits.some(t => t.includes(expectType)), `问法「${q}」应命中「${expectType}」，实际：${hits.join('/')}`).toBe(true)
    }
  })
})
