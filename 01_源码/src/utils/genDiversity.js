export const NATURALIZE_HINT = [
  '【自然化表达】题干背景/场景写具体、像真实考题：可给具体人设/机构/事件/年份地点，避免抽象空话；不要每道都以"近年来/随着……的发展/值得注意的是/有研究表明"这种套路开头；句式长短错落，别连用同一主谓结构。',
  '【去套路干扰项】4 个选项措辞自然、不机械并列；禁止三句都是"不利于/有利于/提高了/促进了"这种同一模板词开头的干扰项；干扰项要像人写的判断句，长度信息量均衡、不一眼暴露。'
]

// 组装出题多样性增量片段：开放换话题防撞 + 自然化 + 与上一题角度差异（一次性注入 ask）
export function diversitySnippet(plate, variant, seq) {
  const parts = []
  const dh = domainHint(plate)
  if (dh) parts.push(dh)
  parts.push(NATURALIZE_HINT[0])
  if (seq % 2 === 1) parts.push(NATURALIZE_HINT[1]) // 一半题目附去套路干扰项提示，避免每次都堆砌同样长指令
  return parts.join('\n')
}

