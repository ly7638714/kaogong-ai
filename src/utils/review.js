// 若模型已输出复盘相关内容则不再追加，避免重复
const HAS_REVIEW = (s) => /复盘|错因自查|回顾/.test(String(s))
// 板块名 → 复盘库键名（对齐 detectBanKuai 返回值）
const PLATE_KEYS = [
  '判断推理', '定义判断', '类比推理', '言语理解', '图形推理',
  '资料分析', '数量关系', '常识判断', '政治理论'
]

/**
 * 生成高效复盘指引
 * @param {string} full  模型回复全文
 * @param {string} bm    板块名（detectBanKuai 返回值，可能为空）
 * @param {string} txt   用户提问文本
 * @returns {string}     追加的复盘指引 markdown（无则返回 ''）
 */
export function buildReview(full, bm, txt) {
  const f = String(full || '')
  // 模型已按 SYS 输出复盘小节 → 以模型为准
  if (HAS_REVIEW(f)) return ''
  // 仅对能识别出板块的做题提问补兜底复盘（闲聊/寒暄不追加）
  const key = PLATE_KEYS.includes(bm) ? bm : ''
  if (!key) return ''
  return REVIEW_BY_PLATE[key] || REVIEW_BY_PLATE.__default
}
