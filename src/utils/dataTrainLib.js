export function cardById(id) {
  return KNOWLEDGE_CARDS.find((c) => c.id === id) || null
}

// 关键词 / 层 / 来源 三条件过滤（空关键词返回全部；条件为 undefined 表示不过滤）
export function searchCards(kw, layer, source) {
  const key = String(kw || '').trim().toLowerCase()
  return KNOWLEDGE_CARDS.filter((c) => {
    if (layer && c.layer !== layer) return false
    if (source && c.source !== source) return false
    if (!key) return true
    const hay = [c.title, c.principle, c.tip, (c.tags || []).join(' ')].join(' ').toLowerCase()
    return hay.includes(key)
  })
}

