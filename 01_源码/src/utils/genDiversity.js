// 组装「开放 + 防撞」提示：告诉模型最近几题是什么 → 换完全不同的话题/素材；
// DOMAIN_POOL 仅作为"一时想不出新话题"时的可选项参考（可参考但不限于）。
export function domainHint(plate) {
  const parts = []
  const recent = recentHeads(plate)
  const recentTxt = recent.slice(0, RECENT_HEAD_N)
  if (recentTxt.length) {
    parts.push('【换话题·避免重复】以下是这个板块最近已出过的' + recentTxt.length + '道题的题干开头：\n' +
      recentTxt.map((h, i) => (i + 1) + '. ' + h + '…').join('\n') +
      '\n本题必须换一个【完全不同的话题 / 素材背景 / 具体案例】，不要与上面任何一道同主题、同背景、同数据来源、同人物事件；选材尽量新颖、有真实感。')
  }
  const pool = domainsFor(plate)
  if (pool.length) {
    // 可选方向参考：随机抽 4 个，措辞永远是"可参考但不限于"——防重复不依赖它，只是给灵感
    const picks = pool.slice().sort(() => Math.random() - 0.5).slice(0, 4)
    parts.push('（若一时想不到新话题，可参考这些方向中的某一个、但不限于：' + picks.join(' / ') + '；不要照抄我上面提示的原话）')
  }
  return parts.join('\n')
}

// ============================================================
// ② 题型轮换器：相邻题型错开 + 非确定性扰动
//    mock 卷同一板块题量较大；单题连续"再来一题"靠它保证相邻题型不同。
//    返回一个函数 nextVariant()：每次调用返回一个与上一题尽量不同的题型。
// ============================================================
export function makeVariantRotator(variants, seedShift = 0) {
  const list = (variants || []).slice()
  if (!list.length) return () => ''
  // 原地洗牌一份作为底层循环（保证每轮覆盖不重不漏），再叠加随机扰动避免固定重复顺序
  let cursor = (Math.floor(Math.random() * list.length) + seedShift) % list.length
  let last = null
  return function nextVariant() {
    if (list.length === 1) return list[0]
    // 找一个与 last 不同的：按洗牌序前进，若碰到 last 就再进一位
    let v = list[cursor % list.length]
    let guard = 0
    while (v === last && guard++ < list.length) { cursor++; v = list[cursor % list.length] }
    last = v
    cursor++
    return v
  }
}

