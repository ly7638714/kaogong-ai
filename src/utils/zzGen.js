// 内置池 + 时政增量池（update-shizheng.mjs 追加）
const POOL = [...FACTS, ...SHIZHENG_EXTRA]
const GEN_TYPES = ['表述匹配', '术语反问', '时间锚点']

export function genZzQuestion(seed) {
  const s = seed == null ? Math.floor(Math.random() * 1e9) : seed
  for (let i = 0; i < 8; i++) {
    const rnd = mulberry(hash(String(s) + '_' + i))
    const fact = POOL[Math.floor(rnd() * POOL.length)]
    const [statement, term, wrongs] = fact
    // 组装四选项：正确术语 + 3个干扰（取自其他条目的正确术语/本条干扰词）
    const pool = POOL.map((f) => f[1]).filter((x) => x !== term)
    const distract = new Set(wrongs)
    while (distract.size < 3 && pool.length) {
      distract.add(pool.splice(Math.floor(rnd() * pool.length), 1)[0])
    }
    if (distract.size < 3) continue
    const opts = [term, ...[...distract].slice(0, 3)]
    const idx = [0, 1, 2, 3]
    for (let j = 3; j > 0; j--) { const k2 = Math.floor(rnd() * (j + 1)); [idx[j], idx[k2]] = [idx[k2], idx[j]] }
    const shuffled = idx.map((x) => opts[x])
    const answer = 'ABCD'[idx.indexOf(0)]
    const type = GEN_TYPES[Math.floor(rnd() * GEN_TYPES.length)]
    const stem =
      type === '术语反问'
        ? `“${term}”的准确内涵/内容对应下列哪一项表述？`
        : `【政治理论·表述核对】“${statement}”。上述内容所对应的概念或表述是：`
    return {
      stem,
      options: shuffled,
      answer,
      explain: `正确答案：${term}。本题考查政治理论表述的精确匹配——${statement.slice(0, 40)}…对应“${term}”。记忆锚点：表述必须与官方原文一致，近似说法均为干扰项。\n\n📌 素材源：官方原文要点（小黑新思想/马原笔记/时政卡集），非杜撰。`,
      cardId: 'zz-matrix',
      variant: '本地题库'
    }
  }
  return null
}

