// 逻辑填空（言语·选词填空）质检误杀回归：短题干+空位标注不被误判
import { describe, it, expect } from 'vitest'
import { plateChecks } from '../utils/quizVerifyProfiles'

const Q = (stem, options, subject = '言语理解', variant = '逻辑填空') => ({ stem, options: options.map((t, i) => ({ k: 'ABCD'[i], t })), answer: 'A', subject })

describe('言语·逻辑填空质检', () => {
  it('短题干（<60字）但标注空位 → 不再被“文段过短”误杀', () => {
    const q = Q('做好古籍数字化要发挥专家作用，____整理与开发之间的空白，____成果的时代价值。', ['填补 彰显', '弥合 挖掘', '链接 放大', '衔接 激活'])
    expect(plateChecks(q, '言语理解', '逻辑填空')).toEqual([])
  })
  it('填空题干缺空位标注 → 提示补空位', () => {
    const q = Q('加快形成新质生产力需要统筹好发展与安全的关系。', ['A 项', 'B 项', 'C 项', 'D 项'])
    const errs = plateChecks(q, '言语理解', '逻辑填空')
    expect(errs.some((e) => e.includes('空位'))).toBe(true)
  })
  it('非填空言语题维持原“完整文段”要求（短文段仍报错）', () => {
    const q = Q('这个观点有些片面。', ['A', 'B', 'C', 'D'], '言语理解', '中心理解')
    const errs = plateChecks(q, '言语理解', '中心理解')
    expect(errs.some((e) => e.includes('完整文段'))).toBe(true)
  })
  it('长文段主旨题不受影响（无错）', () => {
    const long = '近年来，随着数字技术与实体经济的深度融合，传统产业转型升级的步伐明显加快。多地在制造业数字化、服务数字化等领域出台了一批具有含金量的支持政策，企业降本增效成果显著，产业竞争力稳步提升。这段文字意在强调：'
    expect(plateChecks(Q(long, ['A', 'B', 'C', 'D'], '言语理解', '中心理解'), '言语理解', '中心理解')).toEqual([])
  })
  it('v3.8.157 逻辑填空=选词填空：选项写成完整句子 → 判串题不合格', () => {
    const q = Q('事实证明，写好调查研究这篇大文章____。', ['才能把问题找准、把对策提实，使调研成果真正转化为实际成效', '要下足绣花功夫，把情况摸清、把问题找准、把对策提实', '既要有坐板凳的定力，也要有跑田坎的脚力，二者缺一不可', '绝非一日之功，需要久久为功、善作善成，持续用力用劲'])
    const errs = plateChecks(q, '言语理解', '逻辑填空')
    expect(errs.some((e) => e.includes('完整句子') || e.includes('过长'))).toBe(true)
  })
  it('v3.8.157 逻辑填空词/成语组合选项正常放行', () => {
    const q = Q('从“大写意”到“工笔画”，共建“一带一路”倡议的____画卷正在铺展。', ['宏伟、壮阔', '瑰丽、华美', '壮美、恢宏', '绚丽、辉煌'])
    expect(plateChecks(q, '言语理解', '逻辑填空')).toEqual([])
  })
  it('v3.8.157 语句填空（填整句）不被新规则误伤', () => {
    const q = Q('实现碳达峰碳中和是一场广泛而深刻的经济社会系统性变革。____。要把系统观念贯穿“双碳”工作全过程。', ['这是一场硬仗，也是对我们党治国理政能力的一场大考', '涉及生产生活方式的全方位变革，其影响深远', '必须处理好发展和减排、整体和局部、长远目标和短期目标的关系', '我国已进入新发展阶段，推动高质量发展是主题'])
    const errs = plateChecks(q, '言语理解', '语句填空')
    expect(errs.some((e) => e.includes('完整句子') || e.includes('过长'))).toBe(false)
  })
  it('v3.8.163 选词填空：短句（<20字）+ 全角空括号（　）空位 → 放行', () => {
    const q = Q('他向来做事（　）认真细致，从不马虎。', ['一丝不苟、精益求精', '敷衍了事、草草收场', '得过且过、马马虎虎', '粗枝大叶、丢三落四'])
    expect(plateChecks(q, '言语理解', '逻辑填空')).toEqual([])
  })
  it('v3.8.163 语句填空仍要求较长文段（不被放宽误伤）', () => {
    const q = Q('一句话。____。', ['A 项句', 'B 项句', 'C 项句', 'D 项句'])
    const errs = plateChecks(q, '言语理解', '语句填空')
    expect(errs.some((e) => e.includes('过短'))).toBe(true)
  })
})