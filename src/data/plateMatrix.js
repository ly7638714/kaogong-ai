export const SUB_KEYS = Object.keys(SUB_KEYWORDS)

// 文本→(plate6, sub)：先按细分关键词、再回落六大板块检测
export function matchSub(text) {
  const t = String(text || '')
  for (const sub of SUB_KEYS) { const re = SUB_KEYWORDS[sub]; if (re && re.test(t)) return sub }
  return ''
}

// 路由：给出应使用的细分与题型级教练标签（配合 plateCoach/replyProtocol 使用）
export function routePlate(plate6, sub, text) {
  const sub2 = sub || matchSub(text)
  const group = PLATE_TREE[plate6] || {}
  const leaf = sub2 && group[sub2] ? sub2 : (Object.keys(group)[0] || '')
  return { plate6, sub: leaf, types: (group[leaf] || []) }
}