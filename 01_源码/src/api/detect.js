// 板块自动识别：根据题目文本关键词判断所属行测板块
export function detectBanKuai(text) {
  const t = String(text || '')
  if (
    /新思想|五位一体|四个全面|马克思主义|唯物|辩证|哲学|党代会|全会|政府工作报告|习近平新时代中国特色社会主义思想|二十大|二十大报告|马原/.test(
      t
    )
  )
    return '政治理论'
  if (
    /常识|时政|二十四节气|科技成就|法律常识|生活常识|全面建成|周年|纪念日|地理常识|文史常识|科技常识|物理常识|化学常识|生物常识|医学常识|经济常识|宪法|民法典/.test(
      t
    )
  )
    return '常识判断'
  // 图形推理：必须有图形规律/图推专用信号；不能把资料分析的“图形材料/统计图”吞进来
  if (/图推|九宫格|宫格|空间重构|立体图形|展开图|截面图|三视图|一条式|分组分类|一笔画|黑白叠加|去同存异|对称轴|图形规律|图形.*规律|规律.*图形/.test(t))
    return '图形推理'
  // 判断推理：只认明确问法，避免资料分析中的“结论/支持/前提”等泛词抢板
  if (/最能(削弱|加强|支持|质疑|反驳|解释)|以下哪项如果为真|最能解释上述|最可能是上述.*前提|必须假设|前提是|由此(可以)?推出|可以推出的是|真假话|充分条件|必要条件|三段论|翻译推理/.test(t))
    return '判断推理'
  if (/根据上述定义|下列.*属于|下列.*不属于|定义判断|不符合.*定义|属于.*定义|不属于.*定义|下列.*符合.*定义/.test(t))
    return '定义判断'
  if (/对于.*相当于|相对于|与.*关系.*一致|关系.*最为相近|下列.*与.*关系|包含于|种属|组成关系|交叉关系/.test(t))
    return '类比推理'
  // 资料分析：出现统计口径/计算指标，且题干含数据、材料、表格或图表信号时优先
  const dataSignal = /同比|环比|增长率|增长量|年均增长|隔年增长|比重|占比|百分点|基期|现期|平均数|倍数|贡献率|拉动|统计公报|材料中|表中|亿元|万吨|万人/.test(t)
  const dataContext = /\d/.test(t) || /材料|表格|图表|统计图|柱状图|折线图|饼图|数据|指标/.test(t)
  if (dataSignal && dataContext) return '资料分析'
  // 言语理解（意在/主旨/文段等强特征）
  if (/意在|主旨|这段文字|填入|排序|标题|成语|词语|文段|作者|强调|概括|意图|推断/.test(t)) return '言语理解'
  // 泛逻辑词放在资料分析之后：只有没有明确统计计算信号时才按判断推理处理
  if (/削弱|加强|支持|前提|假设|推理|推出|论证|反驳|质疑|结论|假言|因果|论据/.test(t)) return '判断推理'
  if (/同比|环比|增长|比重|平均|倍数|亿元|万吨|百分点|基期|现期|增速|增长率|贡献率|拉动/.test(t)) return '资料分析'
  if (
    /工程|行程|相遇|追及|概率|排列组合|工作效率|工作量|单独完成|合作|同时开工|牛吃草|利润率|生产成本|售价|打折|和差倍比|整除|质数|容斥|最值|抽屉|空瓶|年龄|方阵|钟表|浓度|溶质/.test(
      t
    )
  )
    return '数量关系'
  return ''
}
