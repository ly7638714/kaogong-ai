function variantPassage(base, level = 'entry', seed = 1) {
  const lv = YAN_LEVELS.find((x) => x.k === level) || YAN_LEVELS[0]
  const baseCount = base.sentences.length
  let sentences = base.sentences.slice()
  let roles = base.roles.slice()
  const addBase = lv.k === 'normal' ? 2 : lv.k === 'advanced' ? 5 : lv.k === 'super' ? 9 : 0
  const addRandom = lv.k === 'super' ? (hseed(seed + 311) % 3) : (lv.k === 'normal' || lv.k === 'advanced') ? (hseed(seed + 311) % 2) : 0
  const wanted = Math.max(baseCount, Math.min(14, baseCount + addBase + addRandom))
  const extras = shuffle(extraYanSentences(base), seed + 401)
  const rolePool = ['原因分析：解释问题、现象或观点产生的原因', '过渡衔接：承上启下，把前文引向新话题', '递进深化：在前文基础上强调更进一步的意思', '转折立论：先呈现旧认知/局限，再亮出真实观点']
  let ci = roles.findIndex((r) => String(r).startsWith('结论'))
  if (ci < 0) ci = sentences.length
  let idx = 0
  while (sentences.length < wanted && idx < extras.length) {
    sentences.splice(ci + idx, 0, extras[idx])
    roles.splice(ci + idx, 0, rolePool[hseed(seed + 7 + idx * 13) % rolePool.length])
    idx++
  }
  const chars = textLen(sentences.join(''))
  const out = Object.assign({}, base, {
    difficulty: lv.k,
    difficultyT: lv.t,
    sentCount: sentences.length,
    charCount: chars,
    sentences,
    roles,
    hiddenMeta: lv.k === 'advanced' || lv.k === 'super',
    obscure: lv.k === 'super',
    levelRange: lv.sent + ' / ' + lv.chars
  })
  return out
}
